import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = (p) => readFile(new URL(p, root), 'utf8');
const source = await read('adapters/dsh/client-source.js');
const zh = JSON.parse(await read('locale/zh.json')).ui, en = JSON.parse(await read('locale/en.json')).ui;
const undo = (await read('adapters/dsh/undo-state.mjs')).replace(/^export /gm, '');
const result = '// GENERATED by scripts/build-client.mjs; edit source files instead.\n' + source.replace('/*__UNDO_STATE__*/', undo).replace('/*__TRANSLATIONS__*/ {}', JSON.stringify({ zh, en }));
const target = new URL('adapters/dsh/client.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== result) throw new Error('Client bundle is stale; run npm run build.');
  console.log('Client bundle matches source.');
} else { await writeFile(target, result); console.log('Built DSH client without external dependencies.'); }
